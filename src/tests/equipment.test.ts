test('v5 equipment round trips alongside coins and skills; invalid equipped ownership and slot data fail closed', () => {
    const { p } = setup();
    p.items.emberMantle = 1;
    p.equipment.body = 'emberMantle';
    p.coins = 123;
    const state = { version: 5, profiles: { secret: profileOf(p) }, escrows: [], marketListings: [{ id: 'persistent-order', sellerId: p.publicId, sellerName: p.name, item: 'rangerBoots', quantity: 1, unitPrice: 100, createdAt: 1 }] };
    const recovery = recoverState(JSON.parse(JSON.stringify(state)));
    assert.deepEqual(recovery.marketListings, state.marketListings, 'active auction stock survives the v5 envelope');
    const restored = recovery.profiles.get('secret')!;
    assert.equal(restored.equipment.body, 'emberMantle');
    assert.equal(restored.coins, 123);
    assert.deepEqual(restored.skills, p.skills);
    state.profiles.secret.items.emberMantle = 0;
    assert.throws(() => recoverState(state));
    assert.equal(SHOP.enabled, false);
    assert.ok(SHOP.rules.some(r => r.includes('only auction and duel currency')));
    assert.equal(cleanInput({ aim: Infinity }).aim, undefined);
    assert.ok(Math.abs(cleanInput({ aim: 1000 }).aim!) <= Math.PI);
});
