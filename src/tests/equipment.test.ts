function setup() { const w = new World(); w.raiders = []; const p = createPlayer('a'); p.x = 1000; p.y = 550; w.players.set(p.id, p); return { w, p }; }
test('legacy owned armor migrates once; explicit empty slots and profile copies stay empty', () => {
    const { p } = setup();
    p.items.leatherVest = 2;
    p.items.ironShield = 1;
    p.items.wardCharm = 1;
    const old = profileOf(p) as Partial<ReturnType<typeof profileOf>>;
    delete old.equipment;
    const migrated = createPlayer('b', old);
    assert.equal(gearStats(migrated).armor, 6);
    migrated.equipment.body = null;
    assert.equal(gearStats(createPlayer('c', profileOf(migrated))).armor, 4);
    assert.equal(gearStats(p).armor, 0, 'ownership alone does not equip new goods');
    const normalized = normalizeEquipment(p.items, { body: 'ironShield', offhand: 'phoenixAegis', charm: null, boots: null });
    assert.deepEqual(Object.values(normalized), [null, null, null, null]);
});
test('equipping enforces ownership, slot, bank, life and duel; malformed commands have no effect', () => {
    const { w, p } = setup();
    p.items.emberMantle = 1;
    w.equip(p.id, { slot: 'body', item: 'emberMantle' }, 1000);
    assert.equal(p.equipment.body, null);
    p.x = MAP.bankX;
    p.y = MAP.bankY;
    for (const cmd of [{ slot: 'body', item: 'winterCrown' }, { slot: 'offhand', item: 'emberMantle' }, { slot: '__proto__', item: 'emberMantle' }, { slot: 'body', item: 'fake' }])
        w.equip(p.id, cmd, 1100);
    assert.equal(p.equipment.body, null);
    w.equip(p.id, { slot: 'body', item: 'emberMantle', power: 999999 }, 1200);
    assert.equal(p.equipment.body, 'emberMantle');
    assert.equal(gearStats(p).power, 0);
    p.duelId = 'duel';
    w.equip(p.id, { slot: 'body', item: null }, 1300);
    assert.equal(p.equipment.body, 'emberMantle');
    p.duelId = '';
    p.hp = 0;
    w.equip(p.id, { slot: 'body', item: null }, 1400);
    assert.equal(p.equipment.body, 'emberMantle');
    p.hp = 100;
    w.equip(p.id, { slot: 'body', item: null }, 1500);
    assert.equal(p.equipment.body, null);
});
test('three-piece sets use distinct equipped slots; legendary replacement trades a set bonus for an independent passive', () => {
    const { p } = setup();
    for (const id of ['emberMantle', 'emberGuard', 'emberSigil', 'thunderheart'] as const)
        p.items[id] = 99;
    p.equipment = { body: 'emberMantle', offhand: 'emberGuard', charm: 'emberSigil', boots: null };
    assert.equal(gearStats(p).counts.fire, 3);
    assert.equal(gearStats(p).power, 3);
    assert.equal(gearStats(p).armor, 8);
    p.equipment.offhand = 'thunderheart';
    const s = gearStats(p);
    assert.equal(s.counts.fire, 2);
    assert.equal(s.ranks.fire, 2);
    assert.equal(s.ranks.storm, 3);
    assert.equal(s.power, 4);
    assert.deepEqual(new Set(Object.values(GEAR).map(g => g.rarity)), new Set([1, 2, 3, 4, 5]));
});
test('listing or selling the last equipped item clears only that slot and stops its passive; cancellation does not auto-equip', () => {
    const { w, p } = setup();
    p.x = 800;
    p.items.emberMantle = 1;
    p.equipment.body = 'emberMantle';
    w.market.handle(p.id, { action: 'list', item: 'emberMantle', quantity: 1, unitPrice: 200 }, 1000);
    assert.equal(p.equipment.body, null);
    assert.equal(gearStats(p).ranks.fire, 0);
    w.market.handle(p.id, { action: 'cancel', listingId: w.market.listings[0].id }, 2000);
    assert.equal(p.items.emberMantle, 1);
    assert.equal(p.equipment.body, null);
    p.equipment.body = 'emberMantle';
    w.market.handle(p.id, { action: 'sell', item: 'emberMantle', quantity: 1 }, 3000);
    assert.equal(p.equipment.body, null);
    assert.equal(p.coins, GEAR.emberMantle.sell);
});
