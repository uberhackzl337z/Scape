test('right-click abilities keep their own cooldown without starving basic attacks, and enforce stamina and safe ground', () => {
    for (const weapon of ['sword', 'spear', 'axe'] as const) {
        const { w, p } = setup();
        p.weapon = weapon;
        const e = createEnemy('brute', 'e', 1040, 550);
        w.raiders.push(e);
        p.attackAt = 1150;
        w.ability(p.id, 1000, 0);
        assert.ok(e.hp < 180);
        assert.ok(p.stamina < 100);
        const hp = e.hp;
        w.ability(p.id, 1001, 0);
        w.attack(p, 1001);
        assert.equal(e.hp, hp);
        const recovery = p.abilityAt;
        w.attack(p, 1200);
        assert.ok(e.hp < hp, 'a basic attack works during the secondary cooldown');
        assert.equal(p.abilityAt, recovery, 'basic attacks do not reset the ability cooldown');
        p.x = 800;
        p.abilityAt = p.attackAt = 0;
        p.stamina = 100;
        w.ability(p.id, 10000);
        assert.equal(p.stamina, 100);
    }
});
