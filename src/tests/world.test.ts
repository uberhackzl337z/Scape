test('enemy ground attacks are telegraphed and can be evaded or dodged', () => {
    const world = new World(), p = createPlayer('p');
    p.x = 1040;
    p.y = 550;
    world.players.set(p.id, p);
    const brute = createEnemy('brute', 'brute', 1000, 550);
    world.raiders = [brute];
    world.tick(0, 1000);
    assert.equal(p.hp, 100);
    assert.equal(world.warnings[0].kind, 'slam');
    assert.equal(world.warnings[0].at, 2150);
    p.x = 1000;
    p.y = 700;
    world.resolveWarnings(2150);
    assert.equal(p.hp, 100, 'leaving the warning radius avoids the slam');
    p.x = 1040;
    p.y = 550;
    world.warn(brute, p, 3000);
    world.resolveWarnings(4150);
    assert.equal(p.hp, 70);
    world.warn(brute, p, 5000);
    world.dodge(p, 6100);
    world.resolveWarnings(6150);
    assert.equal(p.hp, 70, 'timed dodge avoids slam damage');
});
