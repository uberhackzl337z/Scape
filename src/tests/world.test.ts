    world.hitEnemy(enemy, p, 1000, 1000);
    assert.equal(p.combatXp, 70);
    assert.equal(p.kills, 1);
    assert.equal(count(p.xp), 0);
    world.hitEnemy(enemy, p, 1000, 1100);
