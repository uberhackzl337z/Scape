test('death drops the haul, keeps banked progress, and respawns after three seconds', () => {
    const world = new World();
    world.raiders = [];
    const p = createPlayer('p');
    world.players.set(p.id, p);
    p.x = 1000;
    p.y = 550;
    p.bag = { wood: 4, ore: 2 };
    p.xp = { wood: 60, ore: 0 };
    p.banked = { wood: 6, ore: 0 };
    world.damage(p, 100, 1000);
    assert.equal(p.hp, 0);
    assert.equal(count(p.bag), 0);
    assert.equal(count(world.loot[0].bag), 6);
    assert.equal(p.xp.wood, 60);
    world.tick(.05, 3999);
    assert.equal(p.hp, 0);
    world.tick(.05, 4000);
    assert.equal(p.hp, 100);
    assert.equal(p.x, 170);
    assert.equal(p.banked.wood, 6);
});
